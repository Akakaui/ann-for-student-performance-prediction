<?php
require_once '../lib/config.php';
require_once '../lib/auth.php';
require_once '../lib/database.php';
require_once '../lib/utils.php';

session_start();
Auth::requireAuth();

// Only lecturers can export batch results
if ($_SESSION['role'] !== 'lecturer') {
    $_SESSION['error'] = "Access denied. This page is for lecturers only.";
    Utils::redirect('dashboard.php');
}

$db = Database::getInstance();
$lecturer_id = $_SESSION['user_id'];

// Get parameters
$group_id = isset($_GET['group_id']) ? intval($_GET['group_id']) : 0;
$export_type = isset($_GET['type']) ? $_GET['type'] : 'full';

// Verify the lecturer owns this group
$group = $db->fetchOne(
    "SELECT * FROM lecturer_groups WHERE id = ? AND lecturer_id = ?",
    [$group_id, $lecturer_id]
);

if (!$group) {
    $_SESSION['error'] = "Group not found or access denied.";
    Utils::redirect('lecturer_groups.php');
}

// Get students in this group
$students = $db->fetchAll("
    SELECT u.id, u.username, u.email, u.created_at as joined_date
    FROM users u 
    JOIN group_students gs ON u.id = gs.student_id 
    WHERE gs.group_id = ? 
    ORDER BY u.username
", [$group_id]);

// Get batch prediction results from session
$batch_results = $_SESSION['batch_results'] ?? [];
$prediction_parameters = $_SESSION['prediction_parameters'] ?? [];

if (empty($batch_results)) {
    // If no session data, try to get from database (for historical exports)
    $batch_results = [];
    foreach ($students as $student) {
        $latest_prediction = $db->fetchOne(
            "SELECT * FROM predictions 
             WHERE user_id = ? 
             ORDER BY created_at DESC 
             LIMIT 1",
            [$student['id']]
        );
        
        if ($latest_prediction) {
            $batch_results[] = [
                'student_id' => $student['id'],
                'student_name' => $student['username'],
                'student_email' => $student['email'],
                'predicted_performance' => $latest_prediction['predicted_performance'],
                'confidence_level' => $latest_prediction['confidence_level'],
                'exam_type' => $latest_prediction['exam_type'],
                'current_cgpa' => $latest_prediction['current_cgpa'],
                'created_at' => $latest_prediction['created_at']
            ];
        }
    }
}

// Calculate statistics
$total_students = count($students);
$students_with_predictions = count($batch_results);
$average_performance = 0;
$average_confidence = 0;
$performance_distribution = [
    'excellent' => 0, 'good' => 0, 'average' => 0, 
    'needs_improvement' => 0, 'poor' => 0
];

if (!empty($batch_results)) {
    $total_performance = 0;
    $total_confidence = 0;
    
    foreach ($batch_results as $result) {
        $performance = $result['predicted_performance'];
        $confidence = $result['confidence_level'];
        
        $total_performance += $performance;
        $total_confidence += $confidence;
        
        if ($performance >= 80) {
            $performance_distribution['excellent']++;
        } elseif ($performance >= 70) {
            $performance_distribution['good']++;
        } elseif ($performance >= 60) {
            $performance_distribution['average']++;
        } elseif ($performance >= 50) {
            $performance_distribution['needs_improvement']++;
        } else {
            $performance_distribution['poor']++;
        }
    }
    
    $average_performance = round($total_performance / count($batch_results), 2);
    $average_confidence = round($total_confidence / count($batch_results), 2);
}

// Prepare CSV data based on export type
$csv_data = [];

if ($export_type === 'summary') {
    // Summary Report
    $csv_data[] = ['BATCH PREDICTION SUMMARY REPORT - ' . strtoupper($group['group_name'])];
    $csv_data[] = ['Generated on:', date('F j, Y \a\t g:i A')];
    $csv_data[] = ['Generated by:', $_SESSION['username']];
    $csv_data[] = [];
    
    $csv_data[] = ['GROUP OVERVIEW'];
    $csv_data[] = ['Group Name:', $group['group_name']];
    $csv_data[] = ['Description:', $group['description'] ?? 'N/A'];
    $csv_data[] = ['Total Students:', $total_students];
    $csv_data[] = ['Students with Predictions:', $students_with_predictions];
    $csv_data[] = ['Students without Data:', $total_students - $students_with_predictions];
    $csv_data[] = [];
    
    $csv_data[] = ['PERFORMANCE SUMMARY'];
    $csv_data[] = ['Average Predicted Performance:', $average_performance . '%'];
    $csv_data[] = ['Average Confidence Level:', $average_confidence . '%'];
    $csv_data[] = [];
    
    $csv_data[] = ['PERFORMANCE DISTRIBUTION'];
    $csv_data[] = ['Category', 'Range', 'Count', 'Percentage'];
    $categories = [
        ['Excellent', '80-100%', $performance_distribution['excellent']],
        ['Good', '70-79%', $performance_distribution['good']],
        ['Average', '60-69%', $performance_distribution['average']],
        ['Needs Improvement', '50-59%', $performance_distribution['needs_improvement']],
        ['Poor', '0-49%', $performance_distribution['poor']]
    ];
    
    foreach ($categories as $category) {
        $percentage = $students_with_predictions > 0 ? 
            round(($category[2] / $students_with_predictions) * 100, 2) : 0;
        $csv_data[] = [
            $category[0],
            $category[1],
            $category[2],
            $percentage . '%'
        ];
    }
    $csv_data[] = [];
    
    $csv_data[] = ['RECOMMENDATIONS'];
    $csv_data[] = ['Priority', 'Count', 'Suggested Action'];
    $csv_data[] = ['High Priority', $performance_distribution['poor'] + $performance_distribution['needs_improvement'], 'Immediate intervention and personalized support'];
    $csv_data[] = ['Medium Priority', $performance_distribution['average'], 'Targeted improvement and monitoring'];
    $csv_data[] = ['Low Priority', $performance_distribution['good'] + $performance_distribution['excellent'], 'Maintenance and enrichment'];
    
} else {
    // Full Detailed Report
    $csv_data[] = ['BATCH PREDICTION DETAILED REPORT - ' . strtoupper($group['group_name'])];
    $csv_data[] = ['Generated on:', date('F j, Y \a\t g:i A')];
    $csv_data[] = ['Generated by:', $_SESSION['username']];
    $csv_data[] = [];
    
    // Summary Section
    $csv_data[] = ['SUMMARY'];
    $csv_data[] = ['Group Name:', $group['group_name']];
    $csv_data[] = ['Total Students:', $total_students];
    $csv_data[] = ['Analyzed Students:', $students_with_predictions];
    $csv_data[] = ['Average Performance:', $average_performance . '%'];
    $csv_data[] = ['Average Confidence:', $average_confidence . '%'];
    $csv_data[] = [];
    
    // Detailed Results
    $csv_data[] = ['DETAILED STUDENT RESULTS'];
    $csv_data[] = [
        'Student Name',
        'Email',
        'Predicted Performance',
        'Confidence Level',
        'Performance Category',
        'Recommendation Priority',
        'Exam Type',
        'Current CGPA',
        'Last Prediction Date'
    ];
    
    foreach ($batch_results as $result) {
        $performance = $result['predicted_performance'];
        
        // Determine category
        if ($performance >= 80) {
            $category = 'Excellent';
        } elseif ($performance >= 70) {
            $category = 'Good';
        } elseif ($performance >= 60) {
            $category = 'Average';
        } elseif ($performance >= 50) {
            $category = 'Needs Improvement';
        } else {
            $category = 'Poor';
        }
        
        // Determine priority
        if ($performance >= 70 && $result['confidence_level'] >= 70) {
            $priority = 'Low';
        } elseif ($performance >= 60 || $result['confidence_level'] >= 60) {
            $priority = 'Medium';
        } else {
            $priority = 'High';
        }
        
        $csv_data[] = [
            $result['student_name'],
            $result['student_email'],
            $performance . '%',
            $result['confidence_level'] . '%',
            $category,
            $priority . ' Priority',
            $result['exam_type'] ?? 'N/A',
            $result['current_cgpa'] ?? 'N/A',
            isset($result['created_at']) ? date('Y-m-d H:i', strtotime($result['created_at'])) : 'N/A'
        ];
    }
    $csv_data[] = [];
    
    // Performance Distribution
    $csv_data[] = ['PERFORMANCE DISTRIBUTION'];
    $csv_data[] = ['Category', 'Range', 'Count', 'Percentage'];
    $categories = [
        ['Excellent', '80-100%', $performance_distribution['excellent']],
        ['Good', '70-79%', $performance_distribution['good']],
        ['Average', '60-69%', $performance_distribution['average']],
        ['Needs Improvement', '50-59%', $performance_distribution['needs_improvement']],
        ['Poor', '0-49%', $performance_distribution['poor']]
    ];
    
    foreach ($categories as $category) {
        $percentage = $students_with_predictions > 0 ? 
            round(($category[2] / $students_with_predictions) * 100, 2) : 0;
        $csv_data[] = [
            $category[0],
            $category[1],
            $category[2],
            $percentage . '%'
        ];
    }
    $csv_data[] = [];
    
    // Students without predictions
    $students_without = array_filter($students, function($student) use ($batch_results) {
        foreach ($batch_results as $result) {
            if ($result['student_id'] == $student['id']) {
                return false;
            }
        }
        return true;
    });
    
    if (!empty($students_without)) {
        $csv_data[] = ['STUDENTS WITHOUT PREDICTION DATA'];
        $csv_data[] = ['Student Name', 'Email', 'Joined Date'];
        foreach ($students_without as $student) {
            $csv_data[] = [
                $student['username'],
                $student['email'],
                date('Y-m-d', strtotime($student['joined_date']))
            ];
        }
        $csv_data[] = [];
    }
    
    // Action Plan
    $csv_data[] = ['RECOMMENDED ACTION PLAN'];
    $csv_data[] = ['Priority Level', 'Student Count', 'Recommended Actions'];
    $csv_data[] = [
        'High Priority',
        $performance_distribution['poor'] + $performance_distribution['needs_improvement'],
        '1. Schedule individual counseling sessions | 2. Develop personalized study plans | 3. Provide additional learning resources | 4. Monitor progress weekly'
    ];
    $csv_data[] = [
        'Medium Priority', 
        $performance_distribution['average'],
        '1. Group study sessions | 2. Targeted skill development | 3. Regular progress checks | 4. Peer mentoring'
    ];
    $csv_data[] = [
        'Low Priority',
        $performance_distribution['good'] + $performance_distribution['excellent'],
        '1. Enrichment activities | 2. Leadership opportunities | 3. Advanced topics | 4. Peer tutoring roles'
    ];
}

// Set headers for CSV download
$filename = "batch_results_" . ($export_type === 'summary' ? 'summary_' : '') . 
            str_replace(' ', '_', $group['group_name']) . "_" . date('Y_m_d') . ".csv";
header('Content-Type: text/csv; charset=utf-8');
header('Content-Disposition: attachment; filename="' . $filename . '"');

// Create output stream
$output = fopen('php://output', 'w');

// Add BOM for Excel compatibility
fputs($output, $bom = (chr(0xEF) . chr(0xBB) . chr(0xBF)));

// Write CSV data
foreach ($csv_data as $row) {
    fputcsv($output, $row);
}

fclose($output);
exit;