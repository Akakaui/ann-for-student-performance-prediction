<?php
require_once '../lib/config.php';
require_once '../lib/auth.php';
require_once '../lib/database.php';
require_once '../lib/utils.php';

session_start();
Auth::requireAuth();

// Only admins can export analytics
if ($_SESSION['role'] !== 'admin') {
    $_SESSION['error'] = "Access denied. This page is for administrators only.";
    Utils::redirect('dashboard.php');
}

$db = Database::getInstance();

// Get comprehensive analytics data
$total_users = $db->fetchOne("SELECT COUNT(*) as count FROM users")['count'];
$total_predictions = $db->fetchOne("SELECT COUNT(*) as count FROM predictions")['count'];
$total_groups = $db->fetchOne("SELECT COUNT(*) as count FROM lecturer_groups")['count'];
$active_lecturers = $db->fetchOne("SELECT COUNT(DISTINCT lecturer_id) as count FROM lecturer_groups")['count'];

// User statistics
$user_stats = $db->fetchAll("
    SELECT 
        role,
        COUNT(*) as count,
        ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM users), 2) as percentage,
        COUNT(CASE WHEN is_verified = 1 THEN 1 END) as verified,
        DATE(MIN(created_at)) as first_registration,
        DATE(MAX(created_at)) as latest_registration
    FROM users 
    GROUP BY role
    ORDER BY count DESC
");

// Prediction statistics
$prediction_stats = $db->fetchAll("
    SELECT 
        exam_type,
        COUNT(*) as count,
        ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM predictions), 2) as percentage,
        AVG(predicted_performance) as avg_performance,
        AVG(confidence_level) as avg_confidence,
        MIN(predicted_performance) as min_performance,
        MAX(predicted_performance) as max_performance
    FROM predictions 
    GROUP BY exam_type
    ORDER BY count DESC
");

// Monthly trends
$monthly_trends = $db->fetchAll("
    SELECT 
        DATE_FORMAT(created_at, '%Y-%m') as month,
        COUNT(*) as predictions,
        COUNT(DISTINCT user_id) as active_users,
        AVG(predicted_performance) as avg_performance,
        AVG(confidence_level) as avg_confidence
    FROM predictions 
    GROUP BY DATE_FORMAT(created_at, '%Y-%m')
    ORDER BY month DESC
    LIMIT 12
");

// Group statistics
$group_stats = $db->fetchAll("
    SELECT 
        lg.group_name,
        u.username as lecturer_name,
        COUNT(DISTINCT gs.student_id) as student_count,
        COUNT(p.id) as prediction_count,
        AVG(p.predicted_performance) as avg_performance
    FROM lecturer_groups lg
    JOIN users u ON lg.lecturer_id = u.id
    LEFT JOIN group_students gs ON lg.id = gs.group_id
    LEFT JOIN predictions p ON gs.student_id = p.user_id
    GROUP BY lg.id, lg.group_name, u.username
    ORDER BY student_count DESC
");

// Performance distribution
$performance_distribution = [
    'excellent' => $db->fetchOne("SELECT COUNT(*) as count FROM predictions WHERE predicted_performance >= 80")['count'],
    'good' => $db->fetchOne("SELECT COUNT(*) as count FROM predictions WHERE predicted_performance >= 70 AND predicted_performance < 80")['count'],
    'average' => $db->fetchOne("SELECT COUNT(*) as count FROM predictions WHERE predicted_performance >= 60 AND predicted_performance < 70")['count'],
    'needs_improvement' => $db->fetchOne("SELECT COUNT(*) as count FROM predictions WHERE predicted_performance >= 50 AND predicted_performance < 60")['count'],
    'poor' => $db->fetchOne("SELECT COUNT(*) as count FROM predictions WHERE predicted_performance < 50")['count']
];

// System metrics
$system_metrics = [
    'database_size' => round($db->fetchOne("SELECT ROUND(SUM(data_length + index_length) / 1024 / 1024, 2) as size FROM information_schema.TABLES WHERE table_schema = DATABASE()")['size'] ?? 0, 2),
    'table_counts' => $db->fetchOne("SELECT COUNT(*) as count FROM information_schema.TABLES WHERE table_schema = DATABASE()")['count'],
    'export_count' => $db->fetchOne("SELECT COUNT(*) as count FROM audit_logs WHERE action_type = 'export'")['count'] ?? 0
];

// Prepare CSV data
$csv_data = [];

// Header section
$csv_data[] = ['STUDENT PERFORMANCE PREDICTOR - COMPREHENSIVE ANALYTICS REPORT'];
$csv_data[] = ['Generated on:', date('F j, Y \a\t g:i A')];
$csv_data[] = ['Generated by:', $_SESSION['username']];
$csv_data[] = [];

// Platform Overview
$csv_data[] = ['PLATFORM OVERVIEW'];
$csv_data[] = ['Total Users:', $total_users];
$csv_data[] = ['Total Predictions:', $total_predictions];
$csv_data[] = ['Student Groups:', $total_groups];
$csv_data[] = ['Active Lecturers:', $active_lecturers];
$csv_data[] = [];

// User Statistics
$csv_data[] = ['USER STATISTICS'];
$csv_data[] = ['Role', 'Count', 'Percentage', 'Verified', 'First Registration', 'Latest Registration'];
foreach ($user_stats as $stat) {
    $csv_data[] = [
        ucfirst($stat['role']),
        $stat['count'],
        $stat['percentage'] . '%',
        $stat['verified'],
        $stat['first_registration'],
        $stat['latest_registration']
    ];
}
$csv_data[] = [];

// Prediction Statistics
$csv_data[] = ['PREDICTION STATISTICS'];
$csv_data[] = ['Exam Type', 'Count', 'Percentage', 'Avg Performance', 'Avg Confidence', 'Min Performance', 'Max Performance'];
foreach ($prediction_stats as $stat) {
    $csv_data[] = [
        $stat['exam_type'],
        $stat['count'],
        $stat['percentage'] . '%',
        round($stat['avg_performance'], 2) . '%',
        round($stat['avg_confidence'], 2) . '%',
        $stat['min_performance'] . '%',
        $stat['max_performance'] . '%'
    ];
}
$csv_data[] = [];

// Performance Distribution
$csv_data[] = ['PERFORMANCE DISTRIBUTION'];
$csv_data[] = ['Category', 'Range', 'Count', 'Percentage'];
$categories = [
    ['Excellent', '80-100%', $performance_distribution['excellent']],
    ['Good', '70-79%', $performance_distribution['good']],
    ['Average', '60-69%', $performance_distribution['average']],
    ['Needs Improvement', '50-59%', $performance_distribution['needs_improvement']],
    ['Poor', '0-49%', $performance_distribution['poor']]
];

foreach ($categories as $category) {
    $percentage = ($category[2] / $total_predictions) * 100;
    $csv_data[] = [
        $category[0],
        $category[1],
        $category[2],
        round($percentage, 2) . '%'
    ];
}
$csv_data[] = [];

// Monthly Trends
$csv_data[] = ['MONTHLY TRENDS (Last 12 Months)'];
$csv_data[] = ['Month', 'Predictions', 'Active Users', 'Avg Performance', 'Avg Confidence'];
foreach ($monthly_trends as $trend) {
    $csv_data[] = [
        $trend['month'],
        $trend['predictions'],
        $trend['active_users'],
        round($trend['avg_performance'], 2) . '%',
        round($trend['avg_confidence'], 2) . '%'
    ];
}
$csv_data[] = [];

// Group Statistics
$csv_data[] = ['GROUP STATISTICS'];
$csv_data[] = ['Group Name', 'Lecturer', 'Students', 'Predictions', 'Avg Performance'];
foreach ($group_stats as $group) {
    $csv_data[] = [
        $group['group_name'],
        $group['lecturer_name'],
        $group['student_count'],
        $group['prediction_count'],
        $group['avg_performance'] ? round($group['avg_performance'], 2) . '%' : 'N/A'
    ];
}
$csv_data[] = [];

// System Metrics
$csv_data[] = ['SYSTEM METRICS'];
$csv_data[] = ['Database Size:', $system_metrics['database_size'] . ' MB'];
$csv_data[] = ['Total Tables:', $system_metrics['table_counts']];
$csv_data[] = ['Exports Generated:', $system_metrics['export_count']];
$csv_data[] = ['Report Generation Time:', date('Y-m-d H:i:s')];

// Set headers for CSV download
$filename = "system_analytics_report_" . date('Y_m_d') . ".csv";
header('Content-Type: text/csv; charset=utf-8');
header('Content-Disposition: attachment; filename="' . $filename . '"');

// Create output stream
$output = fopen('php://output', 'w');

// Add BOM for Excel compatibility
fputs($output, $bom = (chr(0xEF) . chr(0xBB) . chr(0xBF)));

// Write CSV data
foreach ($csv_data as $row) {
    fputcsv($output, $row);
}

fclose($output);
exit;